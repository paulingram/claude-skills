# -*- coding: utf-8 -*-
"""The `gcp-cloud-run` adapter: GENERATES the deployable -- it deploys nothing.

Writes, under ``<workspace>/.architect-team/publish/cloud-run/``:

* ``server.py``   -- a verbatim copy of the local-port token server (stdlib).
* ``Dockerfile``  -- python:3.12-slim running ``server.py serve`` on $PORT 8080
                     with the publish registry + pages snapshot baked in.
* ``deploy.sh``   -- copies the live registry + pages into the build context and
                     runs ``gcloud run deploy`` for the configured project /
                     region / service. A HUMAN runs it.
* ``README.md``   -- what the files are, what running deploy.sh costs and opens.

HONEST BOUNDARY: deploying is a human-approved step that creates a billable,
publicly reachable HTTPS service -- so this adapter never invokes gcloud. The
page is stored in the local pages store (the same store the local-port server
reads), the registry records the would-be URL, and until deploy.sh has run and
``base_url`` is recorded in the config the URL is a PATTERN
(``url_is_pattern: true``), because Cloud Run assigns the hostname at deploy.

Stdlib-only; ASCII-only source.
"""
from __future__ import annotations

import importlib.util
import shlex
from pathlib import Path
from typing import Any, Dict, List, Optional

DEFAULT_SERVICE = "ct6-pages"
DEFAULT_REGION = "us-central1"
CLOUD_RUN_PORT = 8080
GENERATED_DIRNAME = Path(".architect-team") / "publish" / "cloud-run"

_LOCAL_PORT_PATH = Path(__file__).resolve().parent / "local_port.py"


def _local_port():
    spec = importlib.util.spec_from_file_location("ct6_publish_local_port_for_cloud_run", _LOCAL_PORT_PATH)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise ImportError(f"cannot load {_LOCAL_PORT_PATH}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generated_dir(workspace) -> Path:
    return Path(workspace) / GENERATED_DIRNAME


def url_pattern(service: str, region: str, base_url: Optional[str]) -> str:
    if base_url:
        return base_url.rstrip("/")
    return f"https://{service}-<project-hash>-{region}.a.run.app"


def render_dockerfile() -> str:
    return "\n".join([
        "# Generated by CT6 page-publishing (gcp-cloud-run adapter). Stdlib-only image.",
        "FROM python:3.12-slim",
        "WORKDIR /app",
        "COPY server.py /app/server.py",
        "# The publish registry + pages snapshot, copied in by deploy.sh at build time.",
        "COPY home /app/home",
        f"ENV PORT={CLOUD_RUN_PORT}",
        f"EXPOSE {CLOUD_RUN_PORT}",
        'CMD ["python", "/app/server.py", "serve", "--home", "/app/home", '
        f'"--host", "0.0.0.0", "--port", "{CLOUD_RUN_PORT}"]',
        "",
    ])


def render_deploy_script(*, project: str, region: str, service: str, publish_dir: Path) -> str:
    q = shlex.quote
    return "\n".join([
        "#!/usr/bin/env bash",
        "# Generated by CT6 page-publishing (gcp-cloud-run adapter).",
        "# A HUMAN runs this. It creates/updates a PUBLIC, BILLABLE Cloud Run service.",
        "# CT6 never runs it on its own initiative.",
        "set -euo pipefail",
        'cd "$(dirname "$0")"',
        "rm -rf home && mkdir -p home/.architect-team/publish",
        f"cp {q(str(publish_dir / 'registry.json'))} home/.architect-team/publish/registry.json",
        f"cp -R {q(str(publish_dir / 'pages'))} home/.architect-team/publish/pages",
        "gcloud run deploy " + q(service) + " \\",
        "  --source . \\",
        "  --project " + q(project) + " \\",
        "  --region " + q(region) + " \\",
        f"  --port {CLOUD_RUN_PORT} \\",
        "  --allow-unauthenticated \\",
        "  --min-instances 0 --max-instances 2",
        "echo",
        "echo 'Record the printed Service URL as base_url in .architect-team-publish.json'",
        "echo 'so the next publish prints a concrete link instead of the URL pattern.'",
        "",
    ])


def render_readme(*, project: str, region: str, service: str, pattern: str) -> str:
    return "\n".join([
        "# CT6 page-publishing: Cloud Run deployable",
        "",
        "Generated by the `gcp-cloud-run` adapter. **Nothing here has been deployed.**",
        "",
        "- `server.py` is the plugin's stdlib token-checking page server (a copy of",
        "  `scripts/publish/adapters/local_port.py`). It serves only `/<slug>/p/<token>/<page>`",
        "  paths that match a live token in the baked-in registry; everything else is 404.",
        "- `Dockerfile` runs it on port 8080 with the registry + pages snapshot.",
        "- `deploy.sh` snapshots the live registry + pages into `home/` and runs",
        f"  `gcloud run deploy {service} --project {project} --region {region}`.",
        "",
        f"Would-be URL layout: `{pattern}/<slug>/p/<token>/<page>.html`",
        "",
        "## Before you run deploy.sh",
        "",
        "- It creates a publicly reachable HTTPS service that bills per request/CPU-second.",
        "- `--allow-unauthenticated` is what makes a token link openable without a Google login;",
        "  the token in the path is the only access control. Keep TTLs short; revoke early.",
        "- Each new page needs a redeploy (the registry is baked into the image). Re-run deploy.sh",
        "  after publishing, or move the registry + pages to a mounted bucket yourself.",
        "- Record the printed Service URL as `base_url` in `.architect-team-publish.json` so the",
        "  next publish prints a concrete link.",
        "",
    ])


def generate(workspace, *, project: str, region: str, service: str, home=None,
             base_url: Optional[str] = None) -> Dict[str, Any]:
    """Write the deployable; return the file list + the URL pattern."""
    out = generated_dir(workspace)
    out.mkdir(parents=True, exist_ok=True)
    lp = _local_port()
    publish_dir = lp.state_paths(home)["dir"]
    pattern = url_pattern(service, region, base_url)
    files: List[str] = []
    (out / "server.py").write_text(_LOCAL_PORT_PATH.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    files.append(str(out / "server.py"))
    (out / "Dockerfile").write_text(render_dockerfile(), encoding="utf-8", newline="\n")
    files.append(str(out / "Dockerfile"))
    deploy = out / "deploy.sh"
    deploy.write_text(render_deploy_script(project=project, region=region, service=service,
                                           publish_dir=publish_dir), encoding="utf-8", newline="\n")
    try:
        deploy.chmod(deploy.stat().st_mode | 0o111)
    except OSError:
        pass
    files.append(str(deploy))
    (out / ".dockerignore").write_text("*.md\n", encoding="utf-8", newline="\n")
    files.append(str(out / ".dockerignore"))
    (out / "README.md").write_text(render_readme(project=project, region=region, service=service,
                                                 pattern=pattern), encoding="utf-8", newline="\n")
    files.append(str(out / "README.md"))
    return {"dir": str(out), "files": files, "deploy_script": str(deploy), "url_pattern": pattern}


def publish_page(*, page_path, slug: str, token: str, name: str, config: Dict[str, Any],
                 home=None, start_server: bool = True, run=None, now=None,
                 workspace=None) -> Dict[str, Any]:
    """Store the page locally, (re)generate the deployable, return the would-be
    URL. Deploys NOTHING; shells out to NOTHING (``run`` is unused by design)."""
    del start_server, run, now
    gcp = config.get("gcp") or {}
    project = gcp.get("project")
    if not isinstance(project, str) or not project.strip():
        return {"ok": False, "error": "gcp.project is not configured",
                "remediation": "set gcp.project (and optionally gcp.region / gcp.service) in "
                               ".architect-team-publish.json"}
    region = (gcp.get("region") or DEFAULT_REGION).strip()
    service = (gcp.get("service") or DEFAULT_SERVICE).strip()
    lp = _local_port()
    stored = lp.store_page(page_path, slug, token, name, home)
    workspace = Path(workspace) if workspace is not None else Path.cwd()
    gen = generate(workspace, project=project.strip(), region=region, service=service, home=home,
                   base_url=config.get("base_url"))
    path = f"/{slug}/p/{token}/{name}"
    homepage = name == "index.html"
    url = gen["url_pattern"] + (path[: -len("index.html")] if homepage else path)
    return {"ok": True, "url": url, "url_is_pattern": not bool(config.get("base_url")),
            "deployed": False, "path": path, "stored_at": str(stored), "base_url": gen["url_pattern"],
            "scheme": "https", "homepage": homepage, "generated": gen["files"],
            "deploy_script": gen["deploy_script"],
            "warnings": ["deployed NOTHING: a human runs " + gen["deploy_script"] +
                         " (it creates a public, billable Cloud Run service)"]
                        + (["the URL is a PATTERN until deploy.sh has run and base_url is recorded"]
                           if not config.get("base_url") else [])}


def revoke_page(entry: Dict[str, Any], config: Dict[str, Any], home=None, run=None) -> Dict[str, Any]:
    """Remove the local stored copy; the deployed image keeps its snapshot
    until the next deploy.sh run -- said plainly in the result."""
    del run
    lp = _local_port()
    result = lp.revoke_page(entry, config, home)
    result["warnings"] = ["the deployed Cloud Run image still carries its snapshot of this page "
                         "until deploy.sh runs again"]
    return result
